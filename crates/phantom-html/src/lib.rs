//! Independent HTML tokenizer and tree builder for Phantom.
//!
//! At the 2E cycle cutover, the tokenizer -> tree-builder pipeline is the single
//! rendering-facing HTML parser used by Phantom. Compatibility grows from
//! measured WHATWG/WPT-derived cases rather than from a parallel legacy parser.
//!
//! Phantom does not delegate HTML parsing to Chromium, WebKit, Gecko, Servo,
//! or another browser engine.

#![forbid(unsafe_code)]

pub mod tokenizer;
pub mod tree_builder;

use phantom_dom::{Document, DomError};
use thiserror::Error;

use tokenizer::TokenizerError;
use tree_builder::{TreeBuildReport, TreeBuilderError, TreePipelineError, tokenize_and_build};

/// Maximum accepted HTML source size per document.
pub const MAX_HTML_SOURCE_BYTES: usize = 4 * 1024 * 1024;
/// Maximum open-element nesting depth, excluding the synthetic document root.
pub const MAX_HTML_NESTING_DEPTH: usize = 256;
/// Maximum attributes scanned for one start tag.
pub const MAX_ATTRIBUTES_PER_ELEMENT: usize = 128;
/// Maximum aggregate normalized attribute bytes retained for one element.
pub const MAX_ATTRIBUTE_BYTES_PER_ELEMENT: usize = 1024 * 1024;
/// Maximum bytes scanned inside one raw start tag, excluding angle brackets.
pub const MAX_RAW_START_TAG_BYTES: usize = 2 * 1024 * 1024;
/// Maximum bytes retained by one ordinary text node.
pub const MAX_TEXT_NODE_BYTES: usize = 1024 * 1024;
/// Maximum aggregate bytes retained by document text nodes.
pub const MAX_RETAINED_TEXT_BYTES: usize = 3 * 1024 * 1024;
/// Maximum bytes retained by one HTML comment.
pub const MAX_COMMENT_BYTES: usize = 256 * 1024;
/// Maximum bytes retained by one style raw-text body.
pub const MAX_STYLE_BODY_BYTES: usize = 1024 * 1024;

/// Errors produced while transforming HTML into a Phantom DOM.
///
/// The public error surface remains stable across the 2E parser cutover so
/// downstream crates do not need to know whether a fatal admission failure was
/// raised during tokenization or tree construction.
#[derive(Debug, Error, Clone, PartialEq, Eq)]
pub enum HtmlError {
    /// The DOM rejected a requested tree mutation.
    #[error("DOM error: {0}")]
    Dom(#[from] DomError),

    /// The input document exceeded the source admission budget.
    #[error("HTML source exceeds {MAX_HTML_SOURCE_BYTES} bytes")]
    SourceTooLarge,

    /// Open-element nesting exceeded the parser depth budget.
    #[error("HTML nesting exceeds {MAX_HTML_NESTING_DEPTH} elements")]
    NestingTooDeep,

    /// A start tag exceeded the raw scan budget.
    #[error("HTML start tag exceeds {MAX_RAW_START_TAG_BYTES} bytes")]
    StartTagTooLarge,

    /// A start tag contained more attributes than the parser will scan.
    #[error("HTML element exceeds {MAX_ATTRIBUTES_PER_ELEMENT} attributes")]
    TooManyAttributes,

    /// Retained attributes for one element exceeded their byte budget.
    #[error("HTML element attributes exceed {MAX_ATTRIBUTE_BYTES_PER_ELEMENT} bytes")]
    AttributeBytesExceeded,

    /// An ordinary text node exceeded its individual retention budget.
    #[error("HTML text node exceeds {MAX_TEXT_NODE_BYTES} bytes")]
    TextNodeTooLarge,

    /// Aggregate retained text exceeded the document budget.
    #[error("HTML retained text exceeds {MAX_RETAINED_TEXT_BYTES} bytes")]
    RetainedTextTooLarge,

    /// A comment exceeded its individual retention budget.
    #[error("HTML comment exceeds {MAX_COMMENT_BYTES} bytes")]
    CommentTooLarge,

    /// A style body exceeded its raw-text retention budget.
    #[error("HTML style body exceeds {MAX_STYLE_BODY_BYTES} bytes")]
    StyleBodyTooLarge,
}

impl From<TreePipelineError> for HtmlError {
    fn from(error: TreePipelineError) -> Self {
        match error {
            TreePipelineError::Tokenizer(error) => error.into(),
            TreePipelineError::TreeBuilder(error) => error.into(),
        }
    }
}

impl From<TokenizerError> for HtmlError {
    fn from(error: TokenizerError) -> Self {
        match error {
            TokenizerError::SourceTooLarge => Self::SourceTooLarge,
            TokenizerError::StartTagTooLarge => Self::StartTagTooLarge,
            TokenizerError::TooManyAttributes => Self::TooManyAttributes,
            TokenizerError::AttributeBytesExceeded => Self::AttributeBytesExceeded,
            TokenizerError::CommentTooLarge => Self::CommentTooLarge,
            TokenizerError::StyleBodyTooLarge => Self::StyleBodyTooLarge,
        }
    }
}

impl From<TreeBuilderError> for HtmlError {
    fn from(error: TreeBuilderError) -> Self {
        match error {
            TreeBuilderError::Dom(error) => Self::Dom(error),
            TreeBuilderError::NestingTooDeep => Self::NestingTooDeep,
            TreeBuilderError::TextNodeTooLarge => Self::TextNodeTooLarge,
            TreeBuilderError::RetainedTextTooLarge => Self::RetainedTextTooLarge,
        }
    }
}

/// Parses HTML with Phantom's authoritative native pipeline and also returns
/// the bounded structural report generated by that same parse.
///
/// This is the preferred engine integration point at the 2E cutover because the active DOM and its
/// report come from the same tokenizer/tree-builder pass.
///
/// # Errors
///
/// Returns [`HtmlError`] when a deterministic tokenizer, tree-builder, DOM, or
/// inherited 2D security budget is exceeded.
pub fn parse_with_report(source: &str) -> Result<(Document, TreeBuildReport), HtmlError> {
    Ok(tokenize_and_build(source)?.into_parts())
}

/// Parses HTML source into a new Phantom [`Document`].
///
/// From the 2E cycle cutover onward this function is a compatibility convenience wrapper over
/// the authoritative tokenizer -> tree-builder pipeline. There is no separate
/// legacy rendering parser.
///
/// # Errors
///
/// Returns [`HtmlError`] when a deterministic tokenizer, tree-builder, DOM, or
/// inherited 2D security budget is exceeded.
pub fn parse(source: &str) -> Result<Document, HtmlError> {
    let (document, _) = parse_with_report(source)?;
    Ok(document)
}

#[cfg(test)]
mod tests {
    use super::{HtmlError, parse, parse_with_report};
    use phantom_dom::NodeKind;

    #[test]
    fn production_parser_builds_document_structure() -> Result<(), HtmlError> {
        let document = parse("<h1>Phantom</h1><p>Independent engine</p>")?;
        let tags = document
            .nodes()
            .filter_map(|node| match node.kind() {
                NodeKind::Element(element) => Some(element.tag_name()),
                NodeKind::Document | NodeKind::Text(_) | NodeKind::Comment(_) => None,
            })
            .collect::<Vec<_>>();

        assert!(tags.contains(&"html"));
        assert!(tags.contains(&"head"));
        assert!(tags.contains(&"body"));
        assert!(tags.contains(&"h1"));
        assert!(tags.contains(&"p"));
        Ok(())
    }

    #[test]
    fn production_parser_returns_report_from_same_pass() -> Result<(), HtmlError> {
        let (document, report) = parse_with_report("<p>A&amp;B<p>C")?;

        assert_eq!(report.nodes_created, document.len());
        assert_eq!(report.character_references_resolved, 1);
        assert!(report.recoveries_total >= 1);
        Ok(())
    }

    #[test]
    fn production_parser_retains_script_data_for_future_runtime() -> Result<(), HtmlError> {
        let document = parse("<script>if (a < b) {}</script><p>Visible</p>")?;
        let contains_script_text = document
            .nodes()
            .any(|node| matches!(node.kind(), NodeKind::Text(text) if text.contains("if (a < b)")));
        let contains_visible = document
            .nodes()
            .any(|node| matches!(node.kind(), NodeKind::Text(text) if text == "Visible"));

        assert!(contains_script_text);
        assert!(contains_visible);
        Ok(())
    }
}
